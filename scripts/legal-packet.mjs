#!/usr/bin/env node
/**
 * The free legal-review packet (plan W6.37): the documents a university law
 * clinic needs to review Lumen's privacy policy (Amendment 13), Sefaria's
 * terms and the data licences, frozen at one commit.
 *
 *   node scripts/legal-packet.mjs                 # writes dist-legal-packet/ (copies, INDEX.md with SHA-256, data-licences.md)
 *   node scripts/legal-packet.mjs --out <dir>
 *   node scripts/legal-packet.mjs --check         # every document the packet lists exists; the licence list builds
 *
 * The documents are listed in DOCS below. data-licences.md is generated from
 * models/registry.json (every model, its licence, class and commercial use),
 * the bundled data folders' licence files, the eval sets' LICENSE files and
 * Sefaria's per-text rule (src/sources/sefaria/license.ts), so it is never
 * edited by hand.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);

/** The packet, in reading order: [path, what it answers (Hebrew), what it answers (English)]. */
export const DOCS = [
  ["legal/review-packet/README.he.md", "מכתב פתיחה, השאלות שאנחנו שואלים והאינדקס הזה", "Cover note, our questions and this index"],
  ["PRIVACY.he.md", "מדיניות הפרטיות בעברית: מפת הנתונים, הזכויות, תיקון 13, הערכת ההשפעה של שרת השיתוף", "The Hebrew privacy policy: data map, rights, Amendment 13, the share-server impact assessment"],
  ["PRIVACY.md", "אותה מדיניות באנגלית", "The same policy in English"],
  ["docs/src/content/docs/security/privacy-report.md", "דוח הפרטיות שהאפליקציה מפיקה מהפנקס (privacy ledger)", "The privacy report the app builds from its ledger"],
  ["docs/src/content/docs/ai/cloud-routes.md", "מתי תוכן יוצא לשירות ענן, ורק בפעולה של המשתמש", "When content goes to a cloud service, and only on the user's action"],
  ["src/ai/privacyLedger.ts", "הקוד: כל כתובת רשת שהאפליקציה רשאית לפנות אליה, והסיבה", "The code: every network address the app may contact, and why"],
  ["docs/src/content/docs/workspace/jewish-sources.md", "ציטוט מקורות מ-Sefaria: מה מועתק לפתק ומה נשאר קישור", "Quoting Sefaria: what is copied into a note and what stays a link"],
  ["src/sources/sefaria/license.ts", "הקוד: הכלל לפי רישיון של כל טקסט ב-Sefaria", "The code: the per-text licence rule for Sefaria"],
  ["docs/src/content/docs/ai/hebrew-dictation.md", "הכתבה בעברית: המודלים ורישיונותיהם (Ozen, ivrit.ai, Whisper)", "Hebrew dictation: the models and their licences"],
  ["models/registry.json", "רשימת כל המודלים, הרישיון, הסיווג והאם מותר שימוש מסחרי", "Every model, its licence, class and commercial use"],
  ["public/dict/LICENSE.md", "רישיון רשימת המילים העברית שבאפליקציה", "Licence of the bundled Hebrew word list"],
  ["public/lexicon/LICENSE.md", "רישיון המילון העברי (ויקימילון)", "Licence of the Hebrew dictionary (Wiktionary)"],
  ["LICENSE", "הרישיון של Lumen עצמו (MIT)", "Lumen's own licence (MIT)"],
  ["SECURITY.md", "איך מדווחים על חולשה ומה קורה אחר כך", "How a vulnerability is reported and handled"],
  ["legal/review-packet/recommendations.md", "טבלת ההמלצות: כל המלצה הופכת למשימה, בוצעה או נדחתה עם סיבה", "The recommendations table: each one becomes a task, done or declined with a reason"],
];

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const md = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

/** data-licences.md: generated, never edited by hand. */
export function dataLicences(root = ROOT) {
  const reg = JSON.parse(readFileSync(join(root, "models/registry.json"), "utf8"));
  const models = reg.models ?? [];
  const count = (k) => models.filter((m) => m.class === k).length;
  const out = [
    "# Data and model licences (generated by scripts/legal-packet.mjs)",
    "",
    `Lumen's code is MIT. It downloads models on the user's request and bundles a few data files. models/registry.json lists ${models.length} models: ${count("allowed")} allowed, ${count("conditional")} with conditions, ${count("forbidden")} not offered for commercial use, ${count("unknown")} not verified.`,
    "",
    "## Models",
    "",
    "| Model | Kind | Licence | Class | Commercial use | Delivery |",
    "|---|---|---|---|---|---|",
    ...models.map((m) => `| ${md(m.id)} | ${md(m.kind)} | ${md(m.license)} | ${md(m.class)} | ${md(m.commercial)} | ${md(m.delivery ?? "")} |`),
    "",
    "## Data bundled with the app",
    "",
  ];
  for (const f of ["public/dict/LICENSE.md", "public/lexicon/LICENSE.md", "public/tesseract/lang/LICENSE"]) {
    if (!existsSync(join(root, f))) continue;
    const first = readFileSync(join(root, f), "utf8").split("\n").map((l) => l.trim()).filter(Boolean).slice(0, 2).join(" — ").replace(/^#\s*/, "");
    out.push(`- \`${f}\`: ${md(first).slice(0, 240)}`);
  }
  out.push("", "## Evaluation sets (not shipped to users)", "");
  const golden = join(root, "eval/golden");
  if (existsSync(golden))
    for (const d of readdirSync(golden).sort()) {
      const f = join(golden, d, "LICENSE");
      if (!existsSync(f)) continue;
      const parts = [...readFileSync(f, "utf8").matchAll(/^([A-Za-z0-9.+-]+(?:-[A-Za-z0-9.]+)*)\s+—\s+part\(s\):\s*(.+)$/gm)].map((m) => `${m[1]} (${m[2].trim()})`);
      out.push(`- \`eval/golden/${d}\`: ${parts.length ? parts.join("; ") : "see its LICENSE"}`);
    }
  out.push(
    "",
    "## Sefaria",
    "",
    "Sefaria publishes a licence per version of each text. src/sources/sefaria/license.ts copies a text into a note only when it is Public Domain, CC0, CC-BY or CC-BY-SA, with attribution. Every other licence (CC-BY-NC*, \"Copyright…\", or none noted) is a link only: never stored in the vault or cached.",
    "",
  );
  return out.join("\n");
}

/** Only as a command: importing this module (the tests) builds nothing. */
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

function main() {
  const missing = DOCS.filter(([p]) => !existsSync(join(ROOT, p))).map(([p]) => p);
  if (argv.includes("--check")) {
    for (const p of missing) console.log(`✗ ${p} is missing`);
    const lic = dataLicences();
    console.log(missing.length ? "✗ the packet is incomplete" : `✓ legal packet: ${DOCS.length} documents, data-licences.md ${lic.split("\n").length} lines`);
    process.exit(missing.length ? 1 : 0);
  }
  if (missing.length) {
    for (const p of missing) console.log(`✗ ${p} is missing`);
    process.exit(1);
  }
  const out = resolve(argv.includes("--out") ? argv[argv.indexOf("--out") + 1] : join(ROOT, "dist-legal-packet"));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  let commit = "unknown";
  try {
    commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    /* why: not a git checkout */
  }
  const rows = [];
  DOCS.forEach(([p, he, en], i) => {
    const buf = readFileSync(join(ROOT, p));
    const name = `${String(i + 1).padStart(2, "0")}-${p.replace(/\//g, "__")}`;
    writeFileSync(join(out, name), buf);
    rows.push(`| ${i + 1} | \`${name}\` | ${he} | ${en} | \`${sha256(buf).slice(0, 16)}\` |`);
  });
  const lic = dataLicences();
  writeFileSync(join(out, `${String(DOCS.length + 1).padStart(2, "0")}-data-licences.md`), lic + "\n");
  rows.push(`| ${DOCS.length + 1} | \`${String(DOCS.length + 1).padStart(2, "0")}-data-licences.md\` | רשימת רישיונות הנתונים והמודלים (נוצרת אוטומטית) | Data and model licences (generated) | \`${sha256(Buffer.from(lic + "\n")).slice(0, 16)}\` |`);
  const index = [
    "# Lumen — חבילת בדיקה משפטית · Legal review packet",
    "",
    `גרסה: commit \`${commit}\` של https://github.com/talstilkol/lumen-md · Version: commit \`${commit}\`.`,
    "",
    "| # | File | מה זה עונה | What it answers | SHA-256 (first 16) |",
    "|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
  writeFileSync(join(out, "00-INDEX.md"), index);
  console.log(`✓ ${DOCS.length + 1} documents → ${out} (commit ${commit.slice(0, 9)})`);
}
